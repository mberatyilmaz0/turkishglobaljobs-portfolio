type AppIconProps = LucideProps & {
  name: string;
};

export default function AppIcon({ name, size = 20, strokeWidth = 1.8, ...props }: AppIconProps) {
  const normalizedName = name.replace(/\uFE0F/g, '');
  const Icon = ICONS[normalizedName] ?? Circle;

  return <Icon aria-hidden="true" size={size} strokeWidth={strokeWidth} {...props} />;
}
